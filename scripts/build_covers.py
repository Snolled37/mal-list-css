"""Build per-list cover CSS for a MyAnimeList user's anime/manga list.

Replaces malscraper's dead `covers/auto` import (which now serves every title on
MAL: ~14 MB / 116k rules) with only the titles actually on the list.

Usage:  python scripts/build_covers.py [--user Snolled] [--out dist]
Output: dist/covers-anime.css, dist/covers-manga.css

Each rule sets the background of `.data.image a::before` (the hover-cover box),
matching the selector shape the old preset `dataimagelinkbefore` used.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

PAGE = 300  # MAL modern list returns at most 300 rows per load.json call
UA = "mal-list-css cover builder (+https://github.com/)"
# load.json gives a resized, signed URL:
#   https://cdn.myanimelist.net/r/192x272/images/anime/5/83937.jpg?s=...
# The unsigned original is shorter (smaller CSS) and MAL's CDN also serves .webp.
RESIZED = re.compile(r"^https://cdn\.myanimelist\.net/r/\d+x\d+(/images/.+?)\.(?:jpe?g|png|webp)(?:\?.*)?$")


def fetch_list(user: str, kind: str) -> list[dict]:
    items: list[dict] = []
    offset = 0
    while True:
        url = f"https://myanimelist.net/{kind}list/{user}/load.json?offset={offset}&status=7"
        req = urllib.request.Request(url, headers={"User-Agent": UA})
        for attempt in range(4):
            try:
                with urllib.request.urlopen(req, timeout=30) as r:
                    page = json.load(r)
                break
            except Exception as e:  # network hiccup / rate limit
                if attempt == 3:
                    raise
                print(f"  retry {url}: {e}", file=sys.stderr)
                time.sleep(3 * (attempt + 1))
        items.extend(page)
        if len(page) < PAGE:
            return items
        offset += PAGE
        time.sleep(1)  # be polite


def cover_url(raw: str) -> str:
    m = RESIZED.match(raw)
    return f"https://cdn.myanimelist.net{m.group(1)}.webp" if m else raw


def build(kind: str, items: list[dict]) -> str:
    seen: set[int] = set()
    rules: list[str] = []
    for it in sorted(items, key=lambda x: x[f"{kind}_id"]):
        mid = it[f"{kind}_id"]
        img = it.get(f"{kind}_image_path") or ""
        if mid in seen or not img:
            continue
        seen.add(mid)
        rules.append(f'.data.image a[href^="/{kind}/{mid}/"]::before{{background-image:url({cover_url(img)})}}')
    header = f"/* {kind} covers for this list: {len(rules)} titles. Generated by scripts/build_covers.py */\n"
    return header + "\n".join(rules) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", default="Snolled")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "dist"))
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for kind in ("anime", "manga"):
        items = fetch_list(a.user, kind)
        if not items:
            print(f"{kind}: list empty or private - keeping previous file", file=sys.stderr)
            continue
        css = build(kind, items)
        path = out / f"covers-{kind}.css"
        path.write_text(css, encoding="utf-8", newline="\n")
        print(f"{kind}: {css.count('::before')} rules, {path.stat().st_size:,} bytes -> {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
